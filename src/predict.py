"""
Fraud prediction engine supporting individual and batch inference.
Transforms inputs with the trained scaler, computes probability estimates,
applies the optimal validation-tuned threshold, and maps to Low/Medium/High risk tiers.
"""
import os
import json
import uuid
import joblib
import numpy as np
import pandas as pd
from typing import Dict, Any, Tuple, Optional, List

import sys
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from src.preprocessing import FEATURE_COLUMNS, preprocess_input_features

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS_DIR = os.path.join(BASE_DIR, "models")
BEST_MODEL_PATH = os.path.join(MODELS_DIR, "best_fraud_model.joblib")
SCALER_PATH = os.path.join(MODELS_DIR, "scaler.joblib")
METRICS_PATH = os.path.join(MODELS_DIR, "metrics.json")


class FraudPredictor:
    """
    Production-ready inference pipeline for financial transaction risk scoring.
    """
    def __init__(
        self,
        model_path: str = BEST_MODEL_PATH,
        scaler_path: str = SCALER_PATH,
        metrics_path: str = METRICS_PATH
    ):
        self.model_path = model_path
        self.scaler_path = scaler_path
        self.metrics_path = metrics_path
        self.model = None
        self.scaler = None
        self.threshold = 0.5
        self.model_name = "XGBoost"
        self._load_artifacts()

    def _load_artifacts(self):
        """Load trained model, scaler, and threshold metadata."""
        if os.path.exists(self.model_path):
            self.model = joblib.load(self.model_path)
        else:
            print(f"Warning: Model not found at {self.model_path}. Predictions will require training first.")

        if os.path.exists(self.scaler_path):
            self.scaler = joblib.load(self.scaler_path)
        else:
            print(f"Warning: Scaler not found at {self.scaler_path}.")

        if os.path.exists(self.metrics_path):
            try:
                with open(self.metrics_path, "r") as f:
                    metrics = json.load(f)
                    self.threshold = metrics.get("optimal_threshold", 0.5)
                    self.model_name = metrics.get("best_model_name", "XGBoost")
            except Exception as e:
                print(f"Warning loading metrics.json: {e}")

    def is_ready(self) -> bool:
        """Check if both model and scaler are loaded."""
        return self.model is not None and self.scaler is not None

    def determine_risk_level(self, probability: float) -> str:
        """
        Classifies risk into LOW, MEDIUM, HIGH based on tuned threshold.
        - LOW: probability < (threshold * 0.6)
        - MEDIUM: (threshold * 0.6) <= probability < threshold
        - HIGH: probability >= threshold
        """
        if probability >= self.threshold:
            return "HIGH"
        elif probability >= (self.threshold * 0.6):
            return "MEDIUM"
        else:
            return "LOW"

    def predict_single(
        self,
        features: Dict[str, float],
        transaction_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Run inference on a single transaction dictionary.
        Returns risk estimate, prediction label, and probability.
        """
        if not self.is_ready():
            raise RuntimeError("Model or Scaler not loaded. Please train models first.")

        # Ensure transaction ID
        txn_id = transaction_id or f"TXN-{uuid.uuid4().hex[:8].upper()}"
        amount = float(features.get("Amount", 0.0))

        # Build single row DataFrame
        df_input = pd.DataFrame([features])
        df_scaled = preprocess_input_features(df_input, self.scaler)

        # Predict probability
        probs = self.model.predict_proba(df_scaled)[0]
        fraud_prob = float(probs[1]) if len(probs) > 1 else float(probs[0])
        pred_label = 1 if fraud_prob >= self.threshold else 0
        risk_level = self.determine_risk_level(fraud_prob)

        return {
            "transaction_id": txn_id,
            "amount": round(amount, 2),
            "fraud_probability": round(fraud_prob, 4),
            "prediction": pred_label,
            "prediction_label": "Fraudulent" if pred_label == 1 else "Legitimate",
            "risk_level": risk_level,
            "threshold_used": self.threshold,
            "model_used": self.model_name,
            "disclaimer": "Risk estimate generated by AI model. Not a definitive verified determination."
        }

    def predict_batch(
        self,
        df: pd.DataFrame
    ) -> Tuple[pd.DataFrame, Dict[str, Any]]:
        """
        Run inference on batch of transactions.
        Preserves original columns and appends fraud_probability, prediction, and risk_level.
        """
        if not self.is_ready():
            raise RuntimeError("Model or Scaler not loaded. Please train models first.")

        if df.empty:
            raise ValueError("Input DataFrame is empty.")

        # Check required columns
        missing_cols = [c for c in FEATURE_COLUMNS if c not in df.columns]
        if missing_cols:
            raise ValueError(f"Missing required feature columns: {missing_cols}")

        result_df = df.copy()

        # Extract features and preprocess
        df_scaled = preprocess_input_features(df, self.scaler)

        # Batch probability prediction
        probs = self.model.predict_proba(df_scaled)[:, 1]
        preds = (probs >= self.threshold).astype(int)
        risk_levels = [self.determine_risk_level(p) for p in probs]

        # Add transaction_id if not present
        if "transaction_id" not in result_df.columns:
            result_df["transaction_id"] = [f"TXN-{uuid.uuid4().hex[:8].upper()}" for _ in range(len(df))]

        result_df["fraud_probability"] = [round(float(p), 4) for p in probs]
        result_df["prediction"] = preds
        result_df["prediction_label"] = ["Fraudulent" if p == 1 else "Legitimate" for p in preds]
        result_df["risk_level"] = risk_levels

        # Summary statistics
        total_records = len(result_df)
        fraud_records = int((result_df["prediction"] == 1).sum())
        high_risk_cnt = int((result_df["risk_level"] == "HIGH").sum())
        med_risk_cnt = int((result_df["risk_level"] == "MEDIUM").sum())
        low_risk_cnt = int((result_df["risk_level"] == "LOW").sum())
        total_amt = float(result_df["Amount"].sum()) if "Amount" in result_df.columns else 0.0
        flagged_amt = float(result_df[result_df["prediction"] == 1]["Amount"].sum()) if "Amount" in result_df.columns else 0.0

        summary = {
            "total_transactions": total_records,
            "flagged_fraud_count": fraud_records,
            "legitimate_count": total_records - fraud_records,
            "fraud_rate_pct": round((fraud_records / total_records) * 100, 2) if total_records > 0 else 0.0,
            "high_risk_count": high_risk_cnt,
            "medium_risk_count": med_risk_cnt,
            "low_risk_count": low_risk_cnt,
            "total_amount_analyzed": round(total_amt, 2),
            "flagged_fraud_amount": round(flagged_amt, 2),
            "threshold_used": self.threshold,
            "model_name": self.model_name
        }

        return result_df, summary
